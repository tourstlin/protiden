#!/bin/bash
# ============================================================
# 实时查看台灯上位机的所有运行日志（一个窗口看全）
#
# 用法（在板子终端里执行）：
#     bash ~/bthost/watch_logs.sh
#
# 按 Ctrl+C 退出；不会影响正在运行的程序。
# ============================================================

cd "$HOME" || exit 1

echo "=============================================================="
echo " 台灯上位机 · 实时日志面板      $(date '+%H:%M:%S')"
echo "=============================================================="
echo " ▶ agent_console.log : 远程助手（我）执行的每条命令与结果"
echo " ▶ bt_bridge.log     : 蓝牙桥接（连接/断线/自动重连）"
echo " ▶ lamp.log          : 主程序 stdout/stderr（正常时为空）"
echo "--------------------------------------------------------------"
echo " 进程状态："
ps -eo pid,%cpu,%mem,rss,etime,cmd 2>/dev/null \
  | grep -E "[b]t_bridge|[d]esk_lamp" || echo "   （程序当前未运行）"
echo "--------------------------------------------------------------"
echo

# -F：文件被轮转/重建也能继续跟；-n 15：先显示最后 15 行
tail -n 15 -F "$HOME/agent_console.log" "$HOME/bt_bridge.log" "$HOME/lamp.log" 2>/dev/null
